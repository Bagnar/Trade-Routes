def regular_forms(name: str) -> tuple[str, str, str]:
    """Genitive, accusative and prepositional for a one-word regular name."""
    if name.endswith("ия"):
        return name[:-1] + "и", "в " + name[:-1] + "ю", "в " + name[:-1] + "и"
    if name.endswith("ея"):
        return name[:-1] + "и", "в " + name[:-1] + "ю", "в " + name[:-1] + "е"
    if name.endswith("ша") or name.endswith("ча") or name.endswith("жа") or name.endswith("ка") or name.endswith("га") or name.endswith("ха"):
        return name[:-1] + "и", "в " + name[:-1] + "у", "в " + name[:-1] + "е"
    if name.endswith("а"):
        return name[:-1] + "ы", "в " + name[:-1] + "у", "в " + name[:-1] + "е"
    if name.endswith("ь"):  # Бруней-type handled in exceptions; feminine soft sign: Беларусь (exception), Израиль (exception)
        return name[:-1] + "я", "в " + name, "в " + name[:-1] + "е"
    if name.endswith("й"):
        return name[:-1] + "я", "в " + name, "в " + name[:-1] + "е"
    if name.endswith(("о", "у", "и", "е", "э")):  # indeclinable
        return name, "в " + name, "в " + name
    return name + "а", "в " + name, "в " + name + "е"


def main() -> None:
    out = []
    for code, ru, en in BASE:
        if code in EXCEPTIONS:
            gen, acc, loc = EXCEPTIONS[code]
        else:
            gen, acc, loc = regular_forms(ru)
        # Full phrases with prepositions: "из Китая" / "с Кубы", "в Канаду" / "на Кубу", "в Китае" / "на Кубе".
        from_phrase = ("с " if acc.startswith("на ") else "из ") + gen
        out.append({"code": code, "name": ru, "name_en": en, "from": from_phrase, "to": acc, "loc": loc})
    out.sort(key=lambda c: c["name"])
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf8")
    print(f"{len(out)} countries -> {OUT}")


if __name__ == "__main__":
    main()
