def test_code_references_inside_a_heading_are_not_new_rows():
    lines = [
        "Код", "ТН ВЭД Наименование позиции",
        "3004 Лекарственные средства (кроме товаров товарной позиции 3002,",
        "3005 или 3006), состоящие из смешанных или несмешанных продуктов, для",
        "использования в терапевтических целях, расфасованные:",
        "3004 90 000 – прочие:", "3004 90 000 1 – – расфасованные шт 5",
        "1001 Пшеница и меслин:", "1001 99 000 0 – – прочие –", "12",
    ]
    names = reference.parse_ett_pdf_lines(lines)
    assert names["300490"] == "Лекарственные средства (кроме товаров товарной позиции 3002, 3005 или 3006), состоящие из смешанных или несмешанных продуктов, для использования в терапевтических целях, расфасованные: прочие"
    assert names["100199"] == "Пшеница и меслин: прочие"
